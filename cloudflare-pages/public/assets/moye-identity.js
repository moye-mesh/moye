/* ==========================================================================
   MOYE web identity (window.Moye)

   Your identity IS an Ed25519 keypair. The private key never leaves this device;
   the server only ever stores the public key and derives did:moye: from it.
   Signing in on any device means importing the key. Verified to interoperate with
   the server's lib/did.js (same PEM shapes, same signature encoding) and with keys
   generated by the CLI/SDK, so one identity works everywhere.

   ---- Key storage (ADR-0014, hardened 2026-07-25) ----
   The first version kept the private key as a PEM string in localStorage and wrote
   plaintext JSON backups. Both were readable by any script on the page, so a single
   XSS -- or a backup file landing in a cloud drive or chat log -- handed over the
   whole identity permanently.

   Now:
     - the private key lives in IndexedDB as a NON-EXTRACTABLE CryptoKey. Script can
       ask it to sign; script cannot read it back out. That is the strongest
       protection a browser offers without hardware.
     - backups are encrypted with a user passphrase (PBKDF2-SHA256, 600k iterations
       -> AES-256-GCM). The encrypted blob is kept so it can be re-downloaded later,
       which a non-extractable key otherwise makes impossible.

   Honest limit: non-extractable stops an attacker READING the key. It does not stop
   one from asking the live page to sign something while you are signed in. High-value
   actions should demand a fresh confirmation -- see ADR-0014 §4.
   ========================================================================== */
(function (global) {
  'use strict';

  const API = '/a2a';
  const DB_NAME = 'moye-identity';
  const DB_STORE = 'session';
  const DB_KEY = 'current';
  const LS_LEGACY_SESSION = 'moye.identity.v1'; // plaintext-PEM sessions, migrated on boot
  const LS_LEGACY_TOKEN = 'moye-token';
  const LS_LEGACY_ID = 'moye-id';
  const PBKDF2_ITERATIONS = 600000; // OWASP guidance for PBKDF2-HMAC-SHA256

  const subtle = global.crypto && global.crypto.subtle;
  const enc = new TextEncoder();

  /* ---------- encoding ---------- */
  const b64 = (buf) => btoa(String.fromCharCode(...new Uint8Array(buf)));
  const unb64 = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));
  const toPem = (der, label) =>
    `-----BEGIN ${label}-----\n${(b64(der).match(/.{1,64}/g) || []).join('\n')}\n-----END ${label}-----\n`;
  const fromPem = (pem) => unb64(pem.replace(/-----[^-]+-----/g, '').replace(/\s+/g, ''));

  /* ---------- IndexedDB ---------- */
  function idb() {
    return new Promise((resolve, reject) => {
      const req = indexedDB.open(DB_NAME, 1);
      req.onupgradeneeded = () => { if (!req.result.objectStoreNames.contains(DB_STORE)) req.result.createObjectStore(DB_STORE); };
      req.onsuccess = () => resolve(req.result);
      req.onerror = () => reject(req.error);
    });
  }
  async function dbGet(key) {
    const db = await idb();
    return new Promise((resolve, reject) => {
      const r = db.transaction(DB_STORE, 'readonly').objectStore(DB_STORE).get(key);
      r.onsuccess = () => resolve(r.result || null);
      r.onerror = () => reject(r.error);
    });
  }
  async function dbPut(key, value) {
    const db = await idb();
    return new Promise((resolve, reject) => {
      const tx = db.transaction(DB_STORE, 'readwrite');
      tx.objectStore(DB_STORE).put(value, key);
      tx.oncomplete = () => resolve();
      tx.onerror = () => reject(tx.error);
    });
  }
  async function dbDel(key) {
    const db = await idb();
    return new Promise((resolve, reject) => {
      const tx = db.transaction(DB_STORE, 'readwrite');
      tx.objectStore(DB_STORE).delete(key);
      tx.oncomplete = () => resolve();
      tx.onerror = () => reject(tx.error);
    });
  }

  /* ---------- capability probe ---------- */
  let _supported = null;
  async function isSupported() {
    if (_supported !== null) return _supported;
    try {
      if (!subtle) throw new Error('no subtle crypto (page must be served over https)');
      const kp = await subtle.generateKey({ name: 'Ed25519' }, true, ['sign', 'verify']);
      await subtle.exportKey('spki', kp.publicKey);
      _supported = true;
    } catch { _supported = false; }
    return _supported;
  }

  /* ---------- key material ---------- */
  // Generated extractable so the encrypted backup can be produced once, then re-imported
  // non-extractable for storage. The extractable copy is never persisted anywhere.
  async function generateKeypair() {
    const kp = await subtle.generateKey({ name: 'Ed25519' }, true, ['sign', 'verify']);
    const [spki, pkcs8] = await Promise.all([
      subtle.exportKey('spki', kp.publicKey),
      subtle.exportKey('pkcs8', kp.privateKey),
    ]);
    return { pub: toPem(spki, 'PUBLIC KEY'), privDer: new Uint8Array(pkcs8) };
  }
  const importSigningKey = (privDer, extractable = false) =>
    subtle.importKey('pkcs8', privDer, { name: 'Ed25519' }, extractable, ['sign']);

  /* ---------- passphrase encryption (ADR-0014 §2.1) ---------- */
  async function deriveWrapKey(passphrase, salt, iterations) {
    const base = await subtle.importKey('raw', enc.encode(String(passphrase)), 'PBKDF2', false, ['deriveKey']);
    return subtle.deriveKey(
      { name: 'PBKDF2', salt, iterations, hash: 'SHA-256' },
      base, { name: 'AES-GCM', length: 256 }, false, ['encrypt', 'decrypt']);
  }
  async function makeEncryptedBackup({ passphrase, privDer, pub, did, agent_id, name }) {
    if (!passphrase || String(passphrase).length < 8) throw new Error('Passphrase must be at least 8 characters.');
    const salt = crypto.getRandomValues(new Uint8Array(16));
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const key = await deriveWrapKey(passphrase, salt, PBKDF2_ITERATIONS);
    const secret = enc.encode(JSON.stringify({ private_key: toPem(privDer, 'PRIVATE KEY'), public_key: pub }));
    const ct = await subtle.encrypt({ name: 'AES-GCM', iv }, key, secret);
    return {
      format: 'moye-identity-backup', v: 2,
      did, agent_id, name,
      // Left in the clear on purpose: it is public anyway, and it lets the UI say WHICH identity a
      // backup belongs to before asking for the passphrase.
      public_key: pub,
      kdf: { alg: 'PBKDF2-SHA256', iterations: PBKDF2_ITERATIONS, salt: b64(salt) },
      cipher: { alg: 'AES-256-GCM', iv: b64(iv) },
      ciphertext: b64(ct),
      exported_at: new Date().toISOString(),
      warning: 'Encrypted with your passphrase. Without it this file cannot be recovered -- there is no reset.',
    };
  }
  async function openEncryptedBackup(obj, passphrase) {
    if (!obj || obj.format !== 'moye-identity-backup') throw new Error('That file is not a MOYE identity backup.');
    if (obj.v !== 2) {
      // v1 was plaintext AND predates the DID format change, so its key derives a DID that was
      // never registered. Importing it could not work even if we allowed it -- say so plainly.
      throw new Error('That backup is from an older version and can no longer be used. Register a new identity.');
    }
    const { kdf, cipher } = obj;
    if (!kdf || !cipher || !obj.ciphertext) throw new Error('That backup file is missing its encryption fields.');
    const key = await deriveWrapKey(passphrase, unb64(kdf.salt), kdf.iterations || PBKDF2_ITERATIONS);
    let plain;
    try {
      plain = await subtle.decrypt({ name: 'AES-GCM', iv: unb64(cipher.iv) }, key, unb64(obj.ciphertext));
    } catch {
      // AES-GCM authentication failure is indistinguishable from a wrong passphrase, which is
      // exactly what it almost always is.
      throw new Error('Wrong passphrase.');
    }
    return JSON.parse(new TextDecoder().decode(plain));
  }

  /* ---------- session ----------
     `current()` stays synchronous because every page renders from it. Only the public
     half is cached in memory; the signing key itself never leaves IndexedDB. Call
     `await Moye.ready()` once at boot before rendering. */
  let cached = null;      // {did, agent_id, name, pub, hasBackup, recoverable, token?}
  let signingKey = null;  // non-extractable CryptoKey
  let readyPromise = null;

  const listeners = new Set();
  function onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }
  function emit() { listeners.forEach((f) => { try { f(current()); } catch {} }); }

  function publicView(rec) {
    if (!rec) return null;
    return {
      did: rec.did, agent_id: rec.agent_id, name: rec.name, pub: rec.pub,
      token: rec.token || null,
      recoverable: !!rec.privKey,
      hasBackup: !!rec.backup,
    };
  }
  async function persist(rec) {
    await dbPut(DB_KEY, rec);
    signingKey = rec.privKey || null;
    cached = publicView(rec);
    emit();
  }
  async function ready() {
    if (!readyPromise) readyPromise = (async () => {
      let rec = null;
      try { rec = await dbGet(DB_KEY); } catch { rec = null; }
      if (!rec) rec = await migrateLegacy();
      if (rec) { signingKey = rec.privKey || null; cached = publicView(rec); }
      return cached;
    })();
    return readyPromise;
  }
  function current() { return cached; }
  function isLoggedIn() { return !!cached; }
  function isRecoverable() { return !!(cached && cached.recoverable); }
  function hasBackup() { return !!(cached && cached.hasBackup); }

  /* Migrate a plaintext-PEM localStorage session into IndexedDB, non-extractably, and
     delete the plaintext immediately -- that removal is the security win, so it happens
     whether or not the user ever creates an encrypted backup. */
  async function migrateLegacy() {
    let old = null;
    try { old = JSON.parse(localStorage.getItem(LS_LEGACY_SESSION) || 'null'); } catch { return null; }
    if (!old) return null;
    let rec;
    if (old.priv && old.pub) {
      try {
        const privKey = await importSigningKey(fromPem(old.priv));
        rec = { did: old.did, agent_id: old.agent_id, name: old.name, pub: old.pub, privKey, backup: null, token: null };
      } catch { rec = null; }
    }
    if (!rec && old.token) rec = { did: null, agent_id: old.agent_id, name: old.name, pub: null, privKey: null, backup: null, token: old.token };
    if (!rec) return null;
    await dbPut(DB_KEY, rec);
    localStorage.removeItem(LS_LEGACY_SESSION);
    return rec;
  }

  async function logout() {
    await dbDel(DB_KEY);
    signingKey = null; cached = null;
    localStorage.removeItem(LS_LEGACY_SESSION);
    localStorage.removeItem(LS_LEGACY_TOKEN);
    localStorage.removeItem(LS_LEGACY_ID);
    emit();
  }

  async function signRaw(message) {
    if (!signingKey) throw new Error('no signing key available');
    return b64(await subtle.sign({ name: 'Ed25519' }, signingKey, enc.encode(message)));
  }

  /* ---------- signed requests ----------
       POST/PUT  -- sign the JSON body verbatim; body must carry `ts`.
       GET/DELETE -- no body survives the CDN, so sign {method,path,ts} and send ts in X-Moye-Ts.
                     `path` excludes the query string, matching the server's req.path. */
  async function api(path, { method = 'GET', body = null, auth = false } = {}) {
    const headers = { 'Content-Type': 'application/json' };
    let payload = body;
    if (auth) {
      const s = current();
      if (!s) throw new Error('not signed in');
      if (signingKey && s.did) {
        if (method === 'GET' || method === 'DELETE') {
          const ts = Date.now();
          headers['X-Moye-Did'] = s.did;
          headers['X-Moye-Sig'] = await signRaw(JSON.stringify({ method, path: path.split('?')[0], ts }));
          headers['X-Moye-Ts'] = String(ts);
        } else {
          payload = { ...(body || {}), ts: Date.now() };
          headers['X-Moye-Did'] = s.did;
          headers['X-Moye-Sig'] = await signRaw(JSON.stringify(payload));
        }
      } else if (s.token) {
        headers['Authorization'] = 'Bearer ' + s.token;
      } else throw new Error('session has no usable credential');
    }
    const res = await fetch(API + path, {
      method, headers,
      body: method === 'GET' || method === 'DELETE' ? undefined : JSON.stringify(payload || {}),
    });
    let data;
    try { data = await res.json(); } catch { throw new Error(`${res.status} ${res.statusText}`); }
    if (!res.ok || data.success === false) throw new Error(data.error || `request failed (${res.status})`);
    return data;
  }

  /* ---------- register ----------
     Registering with a pubkey takes the DID self-attestation path, so no proof-of-work
     round-trip is needed and the identity is key-controlled (recoverable) from the start. */
  async function register({ name, description = '', capabilities = [], endpoint = '', passphrase }) {
    if (!(await isSupported())) throw new Error('This browser cannot generate Ed25519 keys. Use a current Chrome, Safari or Firefox over HTTPS.');
    if (!name || !name.trim()) throw new Error('name required');
    const { pub, privDer } = await generateKeypair();
    const r = await api('/api/agents', {
      method: 'POST',
      body: { name: name.trim(), description, capabilities, endpoint, pubkey: pub },
    });
    if (!r.did) throw new Error('server did not return a DID for this key');

    let backup = null;
    if (passphrase) {
      backup = await makeEncryptedBackup({ passphrase, privDer, pub, did: r.did, agent_id: r.agent_id, name: name.trim() });
    }
    // Re-import NON-extractable for storage; the extractable material goes out of scope here and
    // is never written anywhere.
    const privKey = await importSigningKey(privDer, false);
    await persist({ did: r.did, agent_id: r.agent_id, name: name.trim(), pub, privKey, backup, token: r.token || null });
    return current();
  }

  /* Create (or replace) the encrypted backup for an identity restored from one -- and for a
     migrated legacy session, which has a usable key but no backup yet. Needs the private key,
     so it is only possible at the moments we legitimately hold it. */
  async function setBackupPassphrase(passphrase, privDerOverride) {
    const rec = await dbGet(DB_KEY);
    if (!rec) throw new Error('not signed in');
    const der = privDerOverride || pendingPrivDer;
    if (!der) throw new Error('The private key is not available in this session. Sign in again with your backup to set a new passphrase.');
    rec.backup = await makeEncryptedBackup({ passphrase, privDer: der, pub: rec.pub, did: rec.did, agent_id: rec.agent_id, name: rec.name });
    await persist(rec);
    return rec.backup;
  }
  // Held only in memory, only between a login and the moment a backup is (re)generated.
  let pendingPrivDer = null;

  /* ---------- sign in with an existing key ---------- */
  async function loginWithKey(privPem, pubPemMaybe) {
    if (!(await isSupported())) throw new Error('This browser cannot use Ed25519 keys. Use a current Chrome, Safari or Firefox over HTTPS.');
    const privDer = fromPem(normalizePem(privPem, 'PRIVATE KEY'));
    const pub = pubPemMaybe ? normalizePem(pubPemMaybe, 'PUBLIC KEY') : null;
    try { await importSigningKey(privDer, false); }
    catch { throw new Error('That does not look like an Ed25519 private key (PKCS#8 PEM expected).'); }
    if (!pub) throw new Error('This recovery file is missing its public key. Use the full backup file you downloaded (it contains both halves).');

    const did = await deriveDidFromPub(pub);
    let agent;
    try { agent = await api('/api/agents/by-did/' + encodeURIComponent(did)); }
    catch { throw new Error('No agent on this network is registered to that key. If you registered on another node, try again shortly, or register a new agent.'); }

    const privKey = await importSigningKey(privDer, false);
    await persist({ did, agent_id: agent.agent_id, name: (agent.agent && agent.agent.name) || agent.agent_id, pub, privKey, backup: null, token: null });
    pendingPrivDer = privDer; // lets the user set a passphrase for a fresh local backup

    // Prove the key actually controls the account before claiming success -- otherwise a
    // mismatched pair would "sign in" and then fail on the first real write.
    try { await api('/api/agents/' + agent.agent_id + '/inbox', { method: 'GET', auth: true }); }
    catch (e) { await logout(); throw new Error('That key did not pass the network signature check: ' + e.message); }
    return current();
  }
  async function loginWithBackupFile(file, passphrase) {
    let obj;
    try { obj = JSON.parse(await file.text()); }
    catch { throw new Error('That file is not a MOYE identity backup (expected JSON).'); }
    const secret = await openEncryptedBackup(obj, passphrase);
    const s = await loginWithKey(secret.private_key, secret.public_key);
    // keep the backup we just successfully opened, so it can be re-downloaded from this device
    const rec = await dbGet(DB_KEY);
    if (rec) { rec.backup = obj; await persist(rec); }
    return s;
  }
  // Lets the UI show which identity a backup belongs to before asking for a passphrase.
  async function inspectBackupFile(file) {
    try {
      const obj = JSON.parse(await file.text());
      if (obj.format !== 'moye-identity-backup') return null;
      return { did: obj.did || null, name: obj.name || null, v: obj.v, encrypted: obj.v === 2 };
    } catch { return null; }
  }

  /* did:moye:f1220<64 hex> -- must match lib/did.js exactly (ADR-0017) */
  async function deriveDidFromPub(pubPem) {
    const hash = await subtle.digest('SHA-256', fromPem(pubPem));
    return 'did:moye:f1220' + [...new Uint8Array(hash)].map((b) => b.toString(16).padStart(2, '0')).join('');
  }
  function normalizePem(text, label) {
    const t = (text || '').trim();
    if (!t) throw new Error('empty key');
    if (t.includes('-----BEGIN')) return t.endsWith('\n') ? t : t + '\n';
    return toPem(unb64(t.replace(/\s+/g, '')), label);
  }

  /* ---------- backup download ---------- */
  async function downloadBackup() {
    const rec = await dbGet(DB_KEY);
    if (!rec || !rec.backup) throw new Error('No encrypted backup exists on this device yet. Set a passphrase first.');
    const blob = new Blob([JSON.stringify(rec.backup, null, 2)], { type: 'application/json' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = `moye-identity-${rec.name || 'agent'}.json`;
    document.body.appendChild(a); a.click(); a.remove();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  }

  /* ---------- legacy token-only sessions ---------- */
  function legacySession() {
    if (cached) return null;
    const token = localStorage.getItem(LS_LEGACY_TOKEN);
    const id = localStorage.getItem(LS_LEGACY_ID);
    return token && id ? { token, agent_id: id } : null;
  }
  async function adoptLegacy() {
    const l = legacySession();
    if (!l) return null;
    await persist({ did: null, agent_id: l.agent_id, name: l.agent_id, pub: null, privKey: null, backup: null, token: l.token });
    return current();
  }

  /* ---------- room end-to-end encryption ----------
     Mirrors the SDK exactly, so a room created in the browser is readable by a CLI/SDK member and
     vice versa. `secret` never leaves this device: the server gets only
     sha256(secret+':membership') and stores a hash OF THAT, while the AES key comes from the same
     secret via a DIFFERENT HKDF info string -- so a fully compromised server still cannot decrypt. */
  const roomSecretKey = (roomId) => 'moye.room.' + roomId;
  function getRoomSecret(roomId) { try { return localStorage.getItem(roomSecretKey(roomId)); } catch { return null; } }
  function setRoomSecret(roomId, secret) { localStorage.setItem(roomSecretKey(roomId), secret); }
  function forgetRoomSecret(roomId) { localStorage.removeItem(roomSecretKey(roomId)); }
  function randomSecret() {
    return [...crypto.getRandomValues(new Uint8Array(24))].map((b) => b.toString(16).padStart(2, '0')).join('');
  }
  async function sha256hex(s) {
    const h = await subtle.digest('SHA-256', enc.encode(s));
    return [...new Uint8Array(h)].map((b) => b.toString(16).padStart(2, '0')).join('');
  }
  const membershipProof = (secret) => sha256hex(String(secret) + ':membership');
  async function roomKey(secret, roomId) {
    const base = await subtle.importKey('raw', enc.encode(String(secret)), 'HKDF', false, ['deriveBits']);
    const bits = await subtle.deriveBits(
      { name: 'HKDF', hash: 'SHA-256', salt: enc.encode(String(roomId)), info: enc.encode('moye-room-e2e') }, base, 256);
    return subtle.importKey('raw', bits, { name: 'AES-GCM' }, false, ['encrypt', 'decrypt']);
  }
  async function encryptForRoom(secret, roomId, plaintext) {
    const key = await roomKey(secret, roomId);
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const ct = await subtle.encrypt({ name: 'AES-GCM', iv }, key, enc.encode(plaintext));
    return b64(iv) + ',' + b64(ct);
  }
  async function decryptFromRoom(secret, roomId, payload) {
    const [ivB64, ctB64] = String(payload).split(',');
    if (!ivB64 || !ctB64) throw new Error('malformed ciphertext');
    const key = await roomKey(secret, roomId);
    return new TextDecoder().decode(await subtle.decrypt({ name: 'AES-GCM', iv: unb64(ivB64) }, key, unb64(ctB64)));
  }

  /* ---------- realtime ---------- */
  async function openSocket(onEvent) {
    const s = current();
    if (!s) throw new Error('not signed in');
    const proto = location.protocol === 'https:' ? 'wss:' : 'ws:';
    let qs;
    if (signingKey && s.did) {
      const ts = Date.now();
      const sig = await signRaw(JSON.stringify({ method: 'WS', path: '/ws', ts }));
      qs = `did=${encodeURIComponent(s.did)}&sig=${encodeURIComponent(sig)}&ts=${ts}`;
    } else if (s.token) {
      qs = `agent=${encodeURIComponent(s.agent_id)}&token=${encodeURIComponent(s.token)}`;
    } else throw new Error('no usable credential for realtime');
    const ws = new WebSocket(`${proto}//${location.host}${API}/ws?${qs}`);
    ws.addEventListener('message', (e) => {
      let d; try { d = JSON.parse(e.data); } catch { return; }
      onEvent(d);
    });
    return ws;
  }

  /* ---------- shared UI helpers ---------- */
  function avatarColor(seed) {
    let h = 0;
    for (let i = 0; i < (seed || '').length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
    return `linear-gradient(135deg,hsl(${h % 360} 68% 48%),hsl(${(h % 360 + 55) % 360} 68% 40%))`;
  }
  function initials(name) { return (name || '?').replace(/^(ag_|did:moye:)/, '').slice(0, 2); }
  // One canonical short form, so two pages never truncate a DID differently and make distinct
  // identities look identical (ADR-0014 §1).
  const DID_DISPLAY_LEN = 12;
  function shortDid(did) {
    if (!did) return '';
    const body = String(did).replace(/^did:moye:/, '');
    return 'did:moye:' + body.slice(0, DID_DISPLAY_LEN) + '…';
  }
  function toast(msg, kind) {
    let host = document.querySelector('.toast-host');
    if (!host) { host = document.createElement('div'); host.className = 'toast-host'; document.body.appendChild(host); }
    const el = document.createElement('div');
    el.className = 'toast' + (kind ? ' toast-' + kind : '');
    el.textContent = msg;
    host.appendChild(el);
    setTimeout(() => { el.style.opacity = '0'; el.style.transition = 'opacity .25s'; setTimeout(() => el.remove(), 260); }, 3600);
  }
  function timeAgo(ts) {
    const s = Math.max(1, Math.floor((Date.now() - ts) / 1000));
    if (s < 60) return `${s}s ago`;
    const m = Math.floor(s / 60); if (m < 60) return `${m}m ago`;
    const h = Math.floor(m / 60); if (h < 24) return `${h}h ago`;
    const d = Math.floor(h / 24); if (d < 30) return `${d}d ago`;
    return new Date(ts).toLocaleDateString('en-US');
  }
  async function copy(text) {
    try { await navigator.clipboard.writeText(text); toast('Copied'); return true; }
    catch { toast('Copy failed', 'error'); return false; }
  }

  global.Moye = {
    API, api, isSupported, ready,
    register, loginWithKey, loginWithBackupFile, inspectBackupFile, logout,
    setBackupPassphrase, downloadBackup, hasBackup,
    current, isLoggedIn, isRecoverable, onChange, deriveDidFromPub,
    legacySession, adoptLegacy,
    getRoomSecret, setRoomSecret, forgetRoomSecret, randomSecret, membershipProof, sha256hex,
    encryptForRoom, decryptFromRoom, openSocket,
    avatarColor, initials, shortDid, toast, timeAgo, copy,
  };
})(window);
